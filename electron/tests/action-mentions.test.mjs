/** Test the shipping DSH source/codec and mention parser without a browser or model. */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const lock = JSON.parse(await readFile(join(root, 'electron/harness.lock.json')));
const upstream = resolve(process.env.CALABASH_HARNESS_SOURCE ?? join(root, 'build/harness', lock.commit));
const base = join(upstream, 'packages/client/calabash-workspace/lib/types');
const { registerActionMentions } = await import(pathToFileURL(join(base, 'client/action-mentions.js')));
let source, language = 'zh', reads = 0;
const catalog = [{ id: 'ai.text', title: 'AI 文本处理', title_en: 'AI text processing', description: '总结、翻译；发送前确认', description_en: 'Summarize and translate; confirm before sending' }];
const ctx = { locale: { getSnapshot: () => ({ active: language }) }, effect: factory => factory(), inputTriggers: { registerSource: value => { source = value; return () => {}; } } };
registerActionMentions(ctx, async () => { reads++; return [...catalog]; });
const request = query => ({ query, quoted: false, drilled: false, signal: new AbortController().signal });
let notifications = 0;
const unsubscribe = source.subscribeLexicon({}, () => { notifications++; });
const menu = await source.candidates({}, request(''));
assert.equal(notifications, 1);
await source.candidates({}, request(''));
assert.equal(notifications, 1, 'unchanged discovery must not cause a menu refresh loop');
assert.equal(menu[0].label, 'AI 文本处理');
assert.equal(menu[0].section, '可用能力');
assert.equal((await source.candidates({}, request('翻译'))).length, 1);
assert.equal((await source.candidates({}, request('action:ai.text'))).length, 1);
assert.equal((await source.candidates({}, request('不存在'))).length, 0);
const pick = source.onPick({ candidate: menu[0] });
assert.equal(pick.insert.ref, '@action:ai.text');
assert.equal(source.codec.clipboardText(pick.insert.ref), '@action:ai.text');
assert.equal(await source.codec.serialize(pick.insert.ref, new AbortController().signal), '@action:ai.text');
assert.deepEqual(await source.candidates({}, { ...request(''), quoted: true }), []);
assert.deepEqual(await source.candidates({}, { ...request(''), drilled: true }), []);
const aborted = new AbortController(); aborted.abort();
assert.deepEqual(await source.candidates({}, { ...request(''), signal: aborted.signal }), []);
await assert.rejects(source.codec.serialize('@action:missing', new AbortController().signal), /不可用/);
language = 'en';
assert.equal((await source.candidates({}, request('text')))[0].label, 'AI text processing');
catalog.push({ id: 'future.example', title: '新增能力', title_en: 'New action', description: '测试', description_en: 'Test' });
assert.equal((await source.candidates({}, request('action'))).length, 2);
catalog.splice(0, 1);
await assert.rejects(source.codec.serialize('@action:ai.text', new AbortController().signal), /unavailable/);
assert.ok(reads > 1);
assert.equal(notifications, 3);
unsubscribe();
console.log('PASS: Action mentions discover registry entries, search, localize, insert, serialize, refresh and reject removed actions without execution');
